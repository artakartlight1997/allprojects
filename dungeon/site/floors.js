// 歩ける マスか（とびらは カギを 持って いる ときだけ act() が 通す）
function walkable(m, x, y) {
  if (x < 0 || y < 0 || x >= MW || y >= MH) return false;
  return m[y][x] === FLOOR || m[y][x] === STAIR;
}

function rnd(n) { return (Math.random() * n) | 0; }
