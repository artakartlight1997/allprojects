// めん 10こ。
//  road … y=7〜11 の 5れつ [はやさ, くるまの ながさ, あいだ]
//         はやさが マイナスなら 左へ 走る
//  river… y=1〜5 の 5れつ [はやさ, 丸太の ながさ, あいだ, しゅるい]
//         しゅるい: 'log' 丸太 / 'turtle' カメ（ときどき しずむ）
//  sec  … 1ぴきぶんの もちじかん
function lane(sp, len, gap, kind) { return { sp: sp, len: len, gap: gap, kind: kind || 'car' }; }

const STAGES = [];
{
  // 1めんの かたち。ここから 少しずつ はやく・すきまを せまく していく。
  //   road  … [はやさ, ながさ, あいだ]  はやさが マイナスなら 左へ
  //   river … [はやさ, ながさ, あいだ, しゅるい]
  // ★ 川は「乗れる ところ」が 半分より 広く ないと、まぐれでしか わたれない。
  //   丸太を 長め・あいだを せまめに して、6わり くらい 乗れる ように した。
  const ROAD = [[1.8, 2, 9], [-1.6, 2, 10], [2.0, 1, 8], [-1.8, 3, 11], [1.5, 2, 9]];
  const RIVER = [[1.6, 6, 4, 'log'], [-1.4, 5, 4, 'turtle'], [1.8, 7, 5, 'log'],
                 [-1.6, 6, 4, 'log'], [1.4, 5, 4, 'turtle']];
  for (let i = 0; i < 10; i++) {
    const k = 1 + i * 0.09;                        // だんだん はやく
    const g = Math.max(0.70, 1 - i * 0.035);       // だんだん すきまが せまく
    STAGES.push({
      name: (i + 1) + ' めん',
      road: ROAD.map((r) => lane(r[0] * k, r[1] + (i >= 6 ? 1 : 0),
                                 Math.max(5, Math.round(r[2] * g)))),
      river: RIVER.map((r) => lane(r[0] * k, r[1] - (i >= 7 ? 1 : 0),
                                   Math.max(4, Math.round(r[2] * (2 - g))), r[3])),
      // ★ もちじかんを みじかく すると「待って わたる」ができず、
      //   かえって むずかしく なる。ゆったり めに して ある。
      sec: Math.max(40, 60 - i * 1.6),
      sink: i >= 4,                                 // カメが しずむ ように なる めん
      homes: i < 3 ? 0 : i < 7 ? 1 : 2,             // つかう おうちの セット
    });
  }
}

