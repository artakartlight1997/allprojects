// 面。おなじ めいろを つかいまわし、だんだん おばけが 速く なる。
//   ps   … あおいの 速さ（マス／びょう）
//   gs   … おばけの 速さ
//   fear … おおきい おかしを 食べた あと、おばけが 逃げる びょう数
//   n    … 出てくる おばけの 数
const STAGES = [];
for (let i = 0; i < 10; i++) {
  STAGES.push({
    name: (i + 1) + ' めん',
    maze: i % MAZES.length,
    // ★ あおいの ほうが はっきり 速い ように する。
    //   同じ くらいの 速さだと 小さい子は 一度も クリアできない。
    ps: 5.8 + i * 0.12,
    gs: 2.4 + i * 0.30,
    fear: Math.max(4.0, 9.0 - i * 0.5),
    n: i < 3 ? 2 : i < 6 ? 3 : 4,
  });
}

