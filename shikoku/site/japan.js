function bounds(list) {
  let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
  for (const p of list) {
    const all = [p.poly].concat(p.isles || []);
    for (const poly of all) {
      for (const [x, y] of poly) {
        if (x < x0) x0 = x;
        if (x > x1) x1 = x;
        if (y < y0) y0 = y;
        if (y > y1) y1 = y;
      }
    }
  }
  return { x0, y0, x1, y1 };
}

// 県の中の「置く目じるし」。
// ★ 頂点の平均だと、長崎のように くねくねした県では **県の外** に出てしまう。
//   作るときに「県の中で いちばん 縁から遠い点」を計算して c に入れてある。
function centroid(p) { return { x: p.c[0], y: p.c[1] }; }


function pointInPoly(poly, x, y) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

// はめる とき の あたり はんてい。
// ★ 本物の形は 細い 半島や 島が あって、ぴったり 中に はなすのは むずかしい。
//   形の中に 入って いなくても、目じるしの 近くなら はまる ことに する。
function hitTol(list) {
  const B = bounds(list || PREFS);
  return (B.x1 - B.x0) * 0.075;
}
function nearPref(p, x, y, tol) {
  if (hitPref(p, x, y)) return true;
  const c = centroid(p);
  return Math.hypot(x - c.x, y - c.y) <= (tol || hitTol());
}

function hitPref(p, x, y) {
  if (pointInPoly(p.poly, x, y)) return true;
  for (const isle of p.isles || []) if (pointInPoly(isle, x, y)) return true;
  return false;
}

